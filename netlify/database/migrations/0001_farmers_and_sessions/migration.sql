-- PostgreSQL schema for the complete app, ported from its SQLite schema.
CREATE TABLE comment_replies (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        comment_id INTEGER NOT NULL,
        farmer_id TEXT NOT NULL,
        body TEXT NOT NULL,
        created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
    );

CREATE TABLE comments (id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, post_id INTEGER NOT NULL, farmer_id TEXT NOT NULL, body TEXT NOT NULL, created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP);

CREATE TABLE conversations (id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, user1_id TEXT NOT NULL, user2_id TEXT NOT NULL, updated_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP);

CREATE TABLE diagnosis_history (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        farmer_id TEXT NOT NULL,
        crop TEXT NOT NULL,
        image_url TEXT NOT NULL,
        status TEXT NOT NULL DEFAULT 'demo',
        result_label TEXT NOT NULL DEFAULT '',
        confidence DOUBLE PRECISION,
        symptoms TEXT NOT NULL DEFAULT '',
        prevention TEXT NOT NULL DEFAULT '',
        treatment TEXT NOT NULL DEFAULT '',
        notes TEXT NOT NULL DEFAULT '',
        created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
    );

CREATE TABLE "farmers" (
                id TEXT PRIMARY KEY, name TEXT NOT NULL, phone TEXT UNIQUE,
                username TEXT UNIQUE NOT NULL, bio TEXT NOT NULL DEFAULT '',
                photo_url TEXT NOT NULL DEFAULT '', created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
                role TEXT NOT NULL DEFAULT 'buyer', blocked INTEGER NOT NULL DEFAULT 0,
                email TEXT UNIQUE, password_hash TEXT
            );

CREATE TABLE follow_requests (
                requester_id TEXT NOT NULL, target_id TEXT NOT NULL, created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
                PRIMARY KEY(requester_id, target_id)
            );

CREATE TABLE follows (follower_id TEXT NOT NULL, followed_id TEXT NOT NULL, PRIMARY KEY(follower_id, followed_id));

CREATE TABLE likes (post_id INTEGER NOT NULL, farmer_id TEXT NOT NULL, PRIMARY KEY(post_id, farmer_id));

CREATE TABLE login_otps (
                phone TEXT PRIMARY KEY, otp_hash TEXT NOT NULL, created_at DOUBLE PRECISION NOT NULL,
                attempts INTEGER NOT NULL DEFAULT 0
            );

CREATE TABLE messages (id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, conversation_id INTEGER NOT NULL, sender_id TEXT NOT NULL, body TEXT NOT NULL, created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP);

CREATE TABLE notifications (id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, farmer_id TEXT NOT NULL, message TEXT NOT NULL, read INTEGER NOT NULL DEFAULT 0, created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP);

CREATE TABLE notifications_v2 (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        farmer_id TEXT NOT NULL,
        kind TEXT NOT NULL DEFAULT 'info',
        message TEXT NOT NULL,
        link TEXT NOT NULL DEFAULT '',
        read INTEGER NOT NULL DEFAULT 0,
        created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
    );

CREATE TABLE post_reports (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        post_id INTEGER NOT NULL,
        farmer_id TEXT NOT NULL,
        reason TEXT NOT NULL DEFAULT 'other',
        details TEXT NOT NULL DEFAULT '',
        status TEXT NOT NULL DEFAULT 'open',
        created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
        UNIQUE(post_id, farmer_id)
    );

CREATE TABLE radio_programs (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        title TEXT NOT NULL,
        title_hi TEXT NOT NULL DEFAULT '',
        host TEXT NOT NULL DEFAULT '',
        category TEXT NOT NULL DEFAULT 'Farming Tips',
        description TEXT NOT NULL DEFAULT '',
        audio_url TEXT NOT NULL DEFAULT '',
        duration_seconds INTEGER NOT NULL DEFAULT 0,
        language TEXT NOT NULL DEFAULT 'Hindi',
        published_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
        active INTEGER NOT NULL DEFAULT 1
    );

CREATE TABLE saved_fields (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        farmer_id TEXT NOT NULL,
        name TEXT NOT NULL,
        crop TEXT NOT NULL DEFAULT '',
        latitude DOUBLE PRECISION NOT NULL,
        longitude DOUBLE PRECISION NOT NULL,
        area_acres DOUBLE PRECISION,
        boundary TEXT NOT NULL DEFAULT '',
        notes TEXT NOT NULL DEFAULT '',
        created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
    );

CREATE TABLE saved_programs (
        program_id INTEGER NOT NULL,
        farmer_id TEXT NOT NULL,
        created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
        PRIMARY KEY(program_id, farmer_id)
    );

CREATE TABLE saves (post_id INTEGER NOT NULL, farmer_id TEXT NOT NULL, PRIMARY KEY(post_id, farmer_id));

CREATE TABLE scheme_bookmarks (
        scheme_id INTEGER NOT NULL,
        farmer_id TEXT NOT NULL,
        created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
        PRIMARY KEY(scheme_id, farmer_id)
    );

CREATE TABLE schemes (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        slug TEXT NOT NULL UNIQUE,
        title TEXT NOT NULL,
        title_hi TEXT NOT NULL DEFAULT '',
        summary TEXT NOT NULL DEFAULT '',
        description TEXT NOT NULL DEFAULT '',
        eligibility TEXT NOT NULL DEFAULT '',
        benefits TEXT NOT NULL DEFAULT '',
        required_documents TEXT NOT NULL DEFAULT '',
        application_process TEXT NOT NULL DEFAULT '',
        official_url TEXT NOT NULL DEFAULT '',
        department TEXT NOT NULL DEFAULT '',
        category TEXT NOT NULL DEFAULT '',
        states TEXT NOT NULL DEFAULT 'All',
        farmer_categories TEXT NOT NULL DEFAULT 'All',
        active INTEGER NOT NULL DEFAULT 1,
        source_note TEXT NOT NULL DEFAULT '',
        updated_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
        created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
    );

CREATE TABLE addresses (
                id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, user_id TEXT NOT NULL, label TEXT NOT NULL DEFAULT 'Home',
                recipient_name TEXT NOT NULL, phone TEXT NOT NULL, line1 TEXT NOT NULL, village TEXT NOT NULL DEFAULT '',
                district TEXT NOT NULL DEFAULT '', state TEXT NOT NULL, postal_code TEXT NOT NULL, is_default INTEGER NOT NULL DEFAULT 0,
                created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP, FOREIGN KEY(user_id) REFERENCES farmers(id)
            );

CREATE TABLE carts (
                id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, buyer_id TEXT NOT NULL UNIQUE,
                created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP, updated_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
                FOREIGN KEY(buyer_id) REFERENCES farmers(id)
            );

CREATE TABLE delivery_partner_profiles (
                user_id TEXT PRIMARY KEY, vehicle_type TEXT NOT NULL DEFAULT '', vehicle_number TEXT NOT NULL DEFAULT '',
                service_area TEXT NOT NULL DEFAULT '', availability_status TEXT NOT NULL DEFAULT 'offline',
                current_lat DOUBLE PRECISION, current_lng DOUBLE PRECISION, verification_status TEXT NOT NULL DEFAULT 'pending',
                rating DOUBLE PRECISION NOT NULL DEFAULT 0, completed_deliveries INTEGER NOT NULL DEFAULT 0,
                FOREIGN KEY(user_id) REFERENCES farmers(id)
            );

CREATE TABLE farmer_profiles (
                user_id TEXT PRIMARY KEY, village TEXT NOT NULL DEFAULT '', district TEXT NOT NULL DEFAULT '',
                state TEXT NOT NULL DEFAULT '', farm_name TEXT NOT NULL DEFAULT '', about TEXT NOT NULL DEFAULT '',
                verification_status TEXT NOT NULL DEFAULT 'pending', rating DOUBLE PRECISION NOT NULL DEFAULT 0,
                review_count INTEGER NOT NULL DEFAULT 0, created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
                FOREIGN KEY(user_id) REFERENCES farmers(id)
            );

CREATE TABLE land_measurements (
                id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, user_id TEXT NOT NULL, name TEXT NOT NULL,
                coordinates TEXT NOT NULL, area_m2 DOUBLE PRECISION NOT NULL, area_ft2 DOUBLE PRECISION NOT NULL,
                acres DOUBLE PRECISION NOT NULL, hectares DOUBLE PRECISION NOT NULL, perimeter_m DOUBLE PRECISION NOT NULL,
                created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
                FOREIGN KEY(user_id) REFERENCES farmers(id)
            );

CREATE TABLE posts (
                id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, farmer_id TEXT NOT NULL,
                kind TEXT NOT NULL CHECK(kind IN ('post', 'reel', 'video')),
                caption TEXT NOT NULL DEFAULT '', media_url TEXT NOT NULL DEFAULT '',
                thumbnail_url TEXT NOT NULL DEFAULT '', title TEXT NOT NULL DEFAULT '',
                description TEXT NOT NULL DEFAULT '', crop TEXT NOT NULL DEFAULT '',
                category TEXT NOT NULL DEFAULT '', language TEXT NOT NULL DEFAULT '',
                tags TEXT NOT NULL DEFAULT '', created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP, media_kind TEXT NOT NULL DEFAULT 'none', report_count INTEGER NOT NULL DEFAULT 0,
                FOREIGN KEY(farmer_id) REFERENCES farmers(id)
            );

CREATE TABLE products (
                id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, owner_id TEXT NOT NULL, name TEXT NOT NULL,
                category TEXT NOT NULL, product_type TEXT NOT NULL, description TEXT NOT NULL DEFAULT '',
                price DOUBLE PRECISION NOT NULL CHECK(price >= 0), unit TEXT NOT NULL, quantity DOUBLE PRECISION NOT NULL CHECK(quantity >= 0),
                min_order_quantity DOUBLE PRECISION NOT NULL DEFAULT 1 CHECK(min_order_quantity > 0), organic INTEGER NOT NULL DEFAULT 0,
                harvest_date TEXT, delivery_time TEXT NOT NULL DEFAULT '', village TEXT NOT NULL DEFAULT '',
                farm_location TEXT NOT NULL DEFAULT '', quality_details TEXT NOT NULL DEFAULT '', status TEXT NOT NULL DEFAULT 'available',
                rating DOUBLE PRECISION NOT NULL DEFAULT 0, review_count INTEGER NOT NULL DEFAULT 0,
                created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP, updated_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
                FOREIGN KEY(owner_id) REFERENCES farmers(id)
            );

CREATE TABLE cart_items (
                cart_id INTEGER NOT NULL, product_id INTEGER NOT NULL, quantity DOUBLE PRECISION NOT NULL CHECK(quantity > 0),
                PRIMARY KEY(cart_id, product_id), FOREIGN KEY(cart_id) REFERENCES carts(id) ON DELETE CASCADE,
                FOREIGN KEY(product_id) REFERENCES products(id)
            );

CREATE TABLE orders (
                id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, order_number TEXT NOT NULL UNIQUE, buyer_id TEXT NOT NULL,
                address_id INTEGER NOT NULL, subtotal DOUBLE PRECISION NOT NULL, delivery_charge DOUBLE PRECISION NOT NULL DEFAULT 0,
                tax DOUBLE PRECISION NOT NULL DEFAULT 0, total DOUBLE PRECISION NOT NULL, payment_status TEXT NOT NULL DEFAULT 'pending',
                status TEXT NOT NULL DEFAULT 'placed', expected_delivery TEXT, created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
                updated_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP, FOREIGN KEY(buyer_id) REFERENCES farmers(id),
                FOREIGN KEY(address_id) REFERENCES addresses(id)
            );

CREATE TABLE product_images (
                id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, product_id INTEGER NOT NULL, image_url TEXT NOT NULL,
                FOREIGN KEY(product_id) REFERENCES products(id) ON DELETE CASCADE
            );

CREATE TABLE wishlists (
                buyer_id TEXT NOT NULL, product_id INTEGER NOT NULL,
                created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
                PRIMARY KEY(buyer_id, product_id), FOREIGN KEY(buyer_id) REFERENCES farmers(id),
                FOREIGN KEY(product_id) REFERENCES products(id) ON DELETE CASCADE
            );

CREATE TABLE delivery_assignments (
                id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, order_id INTEGER NOT NULL UNIQUE, partner_id TEXT,
                status TEXT NOT NULL DEFAULT 'searching', pickup_lat DOUBLE PRECISION, pickup_lng DOUBLE PRECISION,
                assigned_at TEXT, accepted_at TEXT, completed_at TEXT, FOREIGN KEY(order_id) REFERENCES orders(id) ON DELETE CASCADE,
                FOREIGN KEY(partner_id) REFERENCES farmers(id)
            );

CREATE TABLE order_items (
                id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, order_id INTEGER NOT NULL, product_id INTEGER NOT NULL,
                seller_id TEXT NOT NULL, product_name TEXT NOT NULL, unit TEXT NOT NULL, quantity DOUBLE PRECISION NOT NULL,
                unit_price DOUBLE PRECISION NOT NULL, line_total DOUBLE PRECISION NOT NULL, FOREIGN KEY(order_id) REFERENCES orders(id) ON DELETE CASCADE,
                FOREIGN KEY(product_id) REFERENCES products(id), FOREIGN KEY(seller_id) REFERENCES farmers(id)
            );

CREATE TABLE payments (
                id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, order_id INTEGER NOT NULL UNIQUE, provider TEXT NOT NULL DEFAULT 'cod',
                provider_reference TEXT, status TEXT NOT NULL DEFAULT 'pending', amount DOUBLE PRECISION NOT NULL,
                created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP, FOREIGN KEY(order_id) REFERENCES orders(id)
            );

CREATE TABLE reviews (
                id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, product_id INTEGER NOT NULL, order_id INTEGER NOT NULL,
                reviewer_id TEXT NOT NULL, rating INTEGER NOT NULL CHECK(rating BETWEEN 1 AND 5), body TEXT NOT NULL DEFAULT '',
                created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP, UNIQUE(product_id, order_id, reviewer_id),
                FOREIGN KEY(product_id) REFERENCES products(id), FOREIGN KEY(order_id) REFERENCES orders(id),
                FOREIGN KEY(reviewer_id) REFERENCES farmers(id)
            );

CREATE TABLE delivery_locations (
                id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, assignment_id INTEGER NOT NULL, partner_id TEXT NOT NULL,
                latitude DOUBLE PRECISION NOT NULL, longitude DOUBLE PRECISION NOT NULL, recorded_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
                FOREIGN KEY(assignment_id) REFERENCES delivery_assignments(id) ON DELETE CASCADE,
                FOREIGN KEY(partner_id) REFERENCES farmers(id)
            );

CREATE INDEX idx_diagnosis_owner ON diagnosis_history(farmer_id, created_at);

CREATE INDEX idx_fields_owner ON saved_fields(farmer_id, created_at);

CREATE INDEX idx_follow_requests_target ON follow_requests(target_id, created_at DESC);

CREATE INDEX idx_notif_v2_owner ON notifications_v2(farmer_id, read);

CREATE INDEX idx_orders_buyer ON orders(buyer_id, created_at);

CREATE INDEX idx_products_owner ON products(owner_id);

CREATE INDEX idx_products_search ON products(category, product_type, status);

CREATE INDEX idx_replies_comment ON comment_replies(comment_id);

CREATE INDEX idx_reviews_product ON reviews(product_id, created_at);

CREATE INDEX idx_schemes_filter ON schemes(active, category);

ALTER TABLE posts ADD COLUMN IF NOT EXISTS category TEXT NOT NULL DEFAULT 'General';

ALTER TABLE farmers ADD COLUMN IF NOT EXISTS password_hash TEXT;

ALTER TABLE farmers ADD COLUMN IF NOT EXISTS email TEXT UNIQUE;

CREATE TABLE IF NOT EXISTS farmer_sessions (
  token_hash TEXT PRIMARY KEY,
  farmer_id TEXT NOT NULL REFERENCES farmers(id) ON DELETE CASCADE,
  expires_at TIMESTAMPTZ NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS farmer_sessions_expiry_idx ON farmer_sessions (expires_at);

